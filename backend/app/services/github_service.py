"""
GitHub PR Automation Service for OmniSight.
Creates isolated remediation branches, commits validated patches, and opens evidence-backed PRs.
"""

import logging
from datetime import UTC, datetime

from github import Github, GithubException

from app.core.config import settings

logger = logging.getLogger("omnisight.backend.github")


def generate_pr_markdown_description(
    defect_title: str,
    viewport: str,
    target_file: str,
    diff: str,
    verification_status: str = "Verified Fixed in Sandbox",
    before_screenshot_url: str | None = None,
    after_screenshot_url: str | None = None,
    limitations: str | None = None
) -> str:
    """Generates standard Markdown PR body with visual evidence and audit metadata."""
    before_img = f"![Before Fix]({before_screenshot_url})" if before_screenshot_url else "_Evidence captured in local run artifacts._"
    after_img = f"![After Fix]({after_screenshot_url})" if after_screenshot_url else "_Retest screenshot recorded in local run artifacts._"
    limitation_note = limitations or "Patch is strictly scoped to CSS/layout rules and validated against security allowlists."

    return f"""## 🤖 OmniSight Automated Visual QA Fix

### Defect Overview
* **Issue**: {defect_title}
* **Affected Viewport**: `{viewport}`
* **Target File**: `{target_file}`
* **Verification Outcome**: `{verification_status}`

---

### Applied Patch Diff
```diff
{diff}
```

---

### Visual Evidence
| Before Remediation | After Remediation |
| :---: | :---: |
| {before_img} | {after_img} |

---

### Guardrails & Limitations
> [!NOTE]
> {limitation_note}
> Merge decisions remain with the human reviewer.
"""


def create_pull_request_for_fix(
    run_id: str,
    target_file: str,
    file_content: str,
    commit_message: str | None = None,
    pr_title: str | None = None,
    pr_body: str | None = None
) -> str:
    """
    Creates an isolated feature branch, commits the approved file patch, and opens a GitHub PR.
    Falls back gracefully to mock PR simulation if MOCK_GITHUB=True or GITHUB_TOKEN is omitted.
    """
    token = settings.GITHUB_TOKEN
    repo_name = settings.REPO_NAME
    default_commit_msg = commit_message or f"fix(ui): OmniSight auto-repair for {target_file} ({run_id})"
    default_title = pr_title or f"fix(ui): automated visual repair for {run_id}"
    default_body = pr_body or f"Automated visual repair generated by OmniSight for run {run_id}."

    # Graceful mock fallback for offline or development environments
    if settings.MOCK_GITHUB or not token or token in ("your_github_token_here", "dummy_token"):
        logger.info(f"Using mock GitHub service for run {run_id} (token not configured or mock mode enabled).")
        simulated_pr_number = abs(hash(run_id)) % 1000 + 10
        return f"https://github.com/{repo_name}/pull/{simulated_pr_number}"

    try:
        g = Github(token)
        repo = g.get_repo(repo_name)

        default_branch = repo.default_branch
        base_branch_ref = repo.get_branch(default_branch)

        branch_name = f"omnisight-fix-{run_id}"

        # 1. Create fix branch or reuse if existing (idempotent retries)
        try:
            repo.create_git_ref(
                ref=f"refs/heads/{branch_name}",
                sha=base_branch_ref.commit.sha
            )
        except GithubException as ref_err:
            if ref_err.status == 422:
                # Branch already exists; update it to latest base commit
                try:
                    existing_ref = repo.get_git_ref(f"heads/{branch_name}")
                    existing_ref.edit(sha=base_branch_ref.commit.sha, force=True)
                except Exception:
                    # If updating fails, use a unique timestamped branch
                    branch_name = f"omnisight-fix-{run_id}-{int(datetime.now(UTC).timestamp())}"
                    repo.create_git_ref(
                        ref=f"refs/heads/{branch_name}",
                        sha=base_branch_ref.commit.sha
                    )
            else:
                raise

        # 2. Update or create file on branch
        try:
            file_node = repo.get_contents(target_file, ref=branch_name)
            repo.update_file(
                path=target_file,
                message=default_commit_msg,
                content=file_content,
                sha=file_node.sha,
                branch=branch_name
            )
        except GithubException:
            try:
                base_node = repo.get_contents(target_file, ref=default_branch)
                repo.update_file(
                    path=target_file,
                    message=default_commit_msg,
                    content=file_content,
                    sha=base_node.sha,
                    branch=branch_name
                )
            except GithubException:
                repo.create_file(
                    path=target_file,
                    message=default_commit_msg,
                    content=file_content,
                    branch=branch_name
                )

        # 3. Open PR or retrieve existing PR for branch
        try:
            pr = repo.create_pull(
                title=default_title,
                body=default_body,
                head=branch_name,
                base=default_branch
            )
            return pr.html_url
        except GithubException as pr_err:
            if pr_err.status == 422:
                # Check if a PR already exists for this head branch
                pulls = repo.get_pulls(state="open", head=f"{repo.owner.login}:{branch_name}")
                for p in pulls:
                    return p.html_url
            raise


    except Exception as e:
        logger.error(f"GitHub PR automation error for run {run_id}: {e}")
        raise RuntimeError(f"GitHub PR creation failed: {e}") from e